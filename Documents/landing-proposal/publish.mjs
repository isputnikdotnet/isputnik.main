// Publishes the mockup as the live site (the "quick switch" in app-pages-plan.md):
//
//   index.html (this folder)   -> /index.html
//   <slug>.html (generated)    -> /<slug>/index.html      (/photos/, /movies/, …)
//   *.css, *.js                -> /site/
//   sputnik-scene-orbit.png    -> /site/sputnik-scene-orbit.webp
//   shots/*.webp               -> /Assets/screenshots/
//
// Paths become root-absolute (/Assets/…, /site/…, /photos/), the mockup-only bits
// go (noindex, "| Design proposal"). Edit the mockup, then:
//   node build-app-pages.mjs && node publish.mjs
// This folder stays the source; the files it writes at the root are generated.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { apps } from "./apps-data.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const SITE = path.join(root, "site");
const sharp = createRequire("D:/MyProjects/Web/isputnik.home/package.json")("sharp");
const slugs = apps.map((a) => a.slug);
const NOTE = "<!-- Generated from Documents/landing-proposal by publish.mjs — edit there, not here. -->";

function live(html) {
  let s = html;
  s = s.replace(/^\s*<meta name="robots" content="noindex">\r?\n/m, "");
  s = s.replace(/ \| Design proposal<\/title>/, "</title>");
  s = s.replace(/<!-- Generated by build-app-pages\.mjs[^>]*-->\r?\n?/, "");
  s = s.split("../../Assets/").join("/Assets/");
  s = s.replace(/(["'(])shots\//g, "$1/Assets/screenshots/");
  s = s.replace(/href="(proposal|orbit|app-page)\.css"/g, 'href="/site/$1.css"');
  s = s.replace(/src="(proposal|app-page)\.js"/g, 'src="/site/$1.js"');
  s = s.split('href="sputnik-scene-orbit.png"').join('href="/site/sputnik-scene-orbit.webp"');
  for (const slug of slugs) s = s.split(`href="${slug}.html"`).join(`href="/${slug}/"`);
  s = s.replace(/href="index\.html#/g, 'href="/#').split('href="index.html"').join('href="/"');
  s = s.split('<a class="brand" href="#">').join('<a class="brand" href="/">');
  return s.replace(/<!doctype html>/i, (m) => `${m}\n${NOTE}`);
}

const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };

// Pages
write(path.join(root, "index.html"), live(fs.readFileSync(path.join(here, "index.html"), "utf8")));
for (const slug of slugs) {
  write(path.join(root, slug, "index.html"), live(fs.readFileSync(path.join(here, `${slug}.html`), "utf8")));
}

// Styles and scripts
for (const f of ["proposal.css", "orbit.css", "app-page.css", "proposal.js", "app-page.js"]) {
  let text = fs.readFileSync(path.join(here, f), "utf8");
  text = text.split("../../Assets/").join("/Assets/").split('url("sputnik-scene-orbit.png")').join('url("sputnik-scene-orbit.webp")');
  write(path.join(SITE, f), text);
}
await sharp(path.join(here, "sputnik-scene-orbit.png")).webp({ quality: 82 }).toFile(path.join(SITE, "sputnik-scene-orbit.webp"));

// The TV captures the mockup keeps beside it
for (const f of fs.readdirSync(path.join(here, "shots"))) {
  fs.copyFileSync(path.join(here, "shots", f), path.join(root, "Assets/screenshots", f));
}

// Nothing mockup-relative may survive
const leftovers = [];
for (const file of ["index.html", ...slugs.map((s) => `${s}/index.html`), ...["proposal.css", "orbit.css", "app-page.css", "proposal.js", "app-page.js"].map((f) => `site/${f}`)]) {
  const text = fs.readFileSync(path.join(root, file), "utf8");
  for (const bad of ["../../", 'href="index.html', ".html\"", "noindex", "Design proposal", 'src="shots/', '"shots/']) {
    if (text.includes(bad) && !(bad === '.html"' && /https?:[^"]*\.html"/.test(text) && !new RegExp(`href="(?!https?:)[^"]*\\.html"`).test(text))) leftovers.push(`${file}: ${bad}`);
  }
}
console.log(`published / and ${slugs.length} app pages, site/ assets`);
if (leftovers.length) { console.log("LEFTOVERS:\n  " + leftovers.join("\n  ")); process.exitCode = 1; }
